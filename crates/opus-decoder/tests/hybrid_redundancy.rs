use opus_decoder::OpusDecoder;

/// A hybrid packet (fullband, 20 ms) whose redundancy length is more than
/// its frame holds.
const BAD_HYBRID: [u8; 68] = [
    0x68, 0x01, 0x22, 0xcb, 0xd3, 0x6d, 0xe2, 0x31, 0x41, 0xfe, 0xce, 0xf5, 0x89, 0xe8, 0x49, 0xb5,
    0xe7, 0x4c, 0x72, 0x40, 0x37, 0x1d, 0xfe, 0x4e, 0x18, 0x4c, 0xd2, 0x4d, 0x73, 0xff, 0x63, 0x40,
    0x71, 0x15, 0xd1, 0xc8, 0x8b, 0x2e, 0xd5, 0x30, 0x95, 0x51, 0x54, 0x8d, 0x94, 0x47, 0x71, 0x76,
    0x98, 0x11, 0x0e, 0x61, 0x5f, 0xca, 0x32, 0x9f, 0xe2, 0x44, 0xcb, 0x6c, 0xb7, 0x4c, 0xbc, 0x0d,
    0x26, 0xc7, 0x80, 0xe0,
];

#[test]
fn hybrid_redundancy_longer_than_the_frame_is_dropped() {
    let mut decoder = OpusDecoder::new(48_000, 2).expect("decoder");
    let mut out = vec![0.0f32; decoder.max_frame_size_per_channel() * 2];
    let samples = decoder
        .decode_float(&BAD_HYBRID, &mut out, false)
        .expect("decodes");
    assert_eq!(samples, 960, "one 20 ms frame");
}
